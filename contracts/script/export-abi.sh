#!/usr/bin/env bash
# Build, then write the ABI wrappers consumed by the app (PRD §11.5 step 6, BACKLOG A-01).
# Output: app/src/chain/abi/{runBank,street,erc20,faucet,index}.ts
set -euo pipefail
cd "$(dirname "$0")/.."
forge build >/dev/null
OUT="../app/src/chain/abi"
mkdir -p "$OUT"

wrap() { # <const name> <json file> <out file>
  node -e '
    const fs = require("fs");
    const [name, src, dst] = process.argv.slice(1);
    const j = JSON.parse(fs.readFileSync(src, "utf8"));
    const abi = Array.isArray(j) ? j : j.abi;
    fs.writeFileSync(dst, "// Generated by contracts/script/export-abi.sh. Do not edit.\nexport const " + name + " = " + JSON.stringify(abi, null, 2) + " as const;\n");
  ' "$1" "$2" "$3"
}

wrap runBankAbi "out/RunBank.sol/RunBank.json" "$OUT/runBank.ts"
wrap streetAbi  "out/Street.sol/Street.json"   "$OUT/street.ts"

cat > "$OUT/erc20.ts" <<'TS'
export const erc20Abi = [
  { type: 'function', name: 'balanceOf', stateMutability: 'view', inputs: [{ name: 'account', type: 'address' }], outputs: [{ name: '', type: 'uint256' }] },
  { type: 'function', name: 'transfer', stateMutability: 'nonpayable', inputs: [{ name: 'to', type: 'address' }, { name: 'value', type: 'uint256' }], outputs: [{ name: '', type: 'bool' }] },
  { type: 'function', name: 'decimals', stateMutability: 'view', inputs: [], outputs: [{ name: '', type: 'uint8' }] },
  { type: 'function', name: 'symbol', stateMutability: 'view', inputs: [], outputs: [{ name: '', type: 'string' }] },
] as const;
TS

cat > "$OUT/faucet.ts" <<'TS'
export const faucetAbi = [
  { type: 'function', name: 'requestFunds', stateMutability: 'nonpayable', inputs: [{ name: 'recipient', type: 'address' }], outputs: [] },
] as const;
TS

cat > "$OUT/index.ts" <<'TS'
export { runBankAbi } from './runBank';
export { streetAbi } from './street';
export { erc20Abi } from './erc20';
export { faucetAbi } from './faucet';
TS
echo "ABI exported to $OUT"
